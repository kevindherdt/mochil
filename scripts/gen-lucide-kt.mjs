#!/usr/bin/env node
// scripts/gen-lucide-kt.mjs — the web's Lucide glyphs as Compose ImageVectors, so the phone's dock and card badges draw
// the very same shapes as `lucide-react` on the web (ui-overhaul-plan.md: "Lucide as the single icon set").
//
//   node scripts/gen-lucide-kt.mjs            write android/.../ui/kit/LucideIcons.kt
//   node scripts/gen-lucide-kt.mjs --check    fail if the committed file differs (needs `npm ci` in web/ first)
//
// Add a glyph by adding its kebab-case name to ICONS and re-running. Lucide is ISC licensed (the header of every icon file
// in node_modules/lucide-react says so); the licence text must ship with the app (an About / Notices page is a release item in docs/android-ui-plan.md step 8).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const OUT = "android/app/src/main/java/net/kdhmedia/mochil/ui/kit/LucideIcons.kt";
const lucideDir = path.join(root, "web/node_modules/lucide-react/dist/esm/icons");

/** The glyphs the phone uses. The dock first; grow this list with the screen that needs each one. */
const ICONS = [
  "book-open", "compass", "sparkles", "notebook-text", "settings",
  // Settings hub: one glyph per category, plus the chevron and the page back arrow.
  "server", "palette", "library-big", "cloud", "download", "book-open-text", "monitor-play", "shield-check", "chevron-right", "arrow-left",
  // Library header: one glyph per library kind (web/src/features/library/kinds.ts), then search / view menu / layout.
  "headphones", "mic", "clapperboard", "book-image", "eighth-note", "file-text", "search", "layers", "x", "list", "layout-grid", "plus", "info",
];

const pascal = (id) => id.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const n = (value) => String(Number(value));

/** One SVG element → one path string, so Compose needs a single parser. */
function toPath(tag, a) {
  switch (tag) {
    case "path":
      return a.d;
    case "circle": {
      const [cx, cy, r] = [a.cx, a.cy, a.r].map(Number);
      return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0`;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [a.cx, a.cy, a.rx, a.ry].map(Number);
      return `M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(2 * rx)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-2 * rx)} 0`;
    }
    case "rect": {
      const [x, y, w, h] = [a.x, a.y, a.width, a.height].map(Number);
      const rx = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(Number(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx && !ry) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
      return `M${n(x + rx)} ${n(y)}h${n(w - 2 * rx)}a${n(rx)} ${n(ry)} 0 0 1 ${n(rx)} ${n(ry)}v${n(h - 2 * ry)}a${n(rx)} ${n(ry)} 0 0 1 ${n(-rx)} ${n(ry)}h${n(-(w - 2 * rx))}a${n(rx)} ${n(ry)} 0 0 1 ${n(-rx)} ${n(-ry)}v${n(-(h - 2 * ry))}a${n(rx)} ${n(ry)} 0 0 1 ${n(rx)} ${n(-ry)}z`;
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
      return `M${a.points.trim().replace(/\s+/g, "L")}`;
    case "polygon":
      return `M${a.points.trim().replace(/\s+/g, "L")}z`;
    default:
      throw new Error(`gen-lucide-kt: unsupported <${tag}>`);
  }
}

function load(id) {
  const file = path.join(lucideDir, `${id}.mjs`);
  if (!existsSync(file)) throw new Error(`gen-lucide-kt: ${id} not found in ${lucideDir} — run npm ci in web/ first`);
  const source = readFileSync(file, "utf8");
  const match = source.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!match) throw new Error(`gen-lucide-kt: no __iconData in ${file}`);
  const data = new Function(`return ${match[1]}`)();
  if (data.size !== 24) throw new Error(`gen-lucide-kt: ${id} is not a 24-unit glyph`);
  return data.node.map(([tag, attrs]) => toPath(tag, attrs));
}

const kotlinString = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

function render() {
  const entries = ICONS.map((id) => ({ id, name: pascal(id), paths: load(id) }));
  const props = entries.map((e) => `    val ${e.name}: ImageVector by lazy { lucide(${kotlinString(e.id)}, PATHS.getValue(${kotlinString(e.id)})) }`).join("\n");
  const table = entries
    .map((e) => `        ${kotlinString(e.id)} to listOf(\n${e.paths.map((p) => `            ${kotlinString(p)},`).join("\n")}\n        ),`)
    .join("\n");
  return `// GENERATED by scripts/gen-lucide-kt.mjs from lucide-react (ISC licence). Do not hand-edit — add the glyph to ICONS there.
//
// The same shapes the web draws, as 24-unit stroke vectors. Draw them with Icon(tint = …): the stroke colour in the vector is
// a placeholder that Icon replaces.
package net.kdhmedia.mochil.ui.kit

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

internal object LucideIcons {
${props}

    /** The same glyph with another stroke weight: the dock draws at 1.8 where Lucide's default is 2. */
    fun withStroke(id: String, strokeWidth: Float): ImageVector = lucide(id, PATHS.getValue(id), strokeWidth)

    private fun lucide(id: String, paths: List<String>, strokeWidth: Float = 2f): ImageVector {
        val builder = ImageVector.Builder(id, 24.dp, 24.dp, 24f, 24f)
        paths.forEach { d ->
            builder.addPath(
                pathData = PathParser().parsePathString(d).toNodes(),
                fill = null,
                stroke = SolidColor(Color.Black),
                strokeLineWidth = strokeWidth,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
        return builder.build()
    }

    private val PATHS: Map<String, List<String>> = mapOf(
${table}
    )
}
`;
}

const content = render();
const abs = path.join(root, OUT);
const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
if (current === content) {
  console.log(`unchanged  ${OUT}`);
} else if (CHECK) {
  console.error(`DRIFT      ${OUT} does not match lucide-react — run: node scripts/gen-lucide-kt.mjs`);
  process.exit(1);
} else {
  writeFileSync(abs, content, "utf8");
  console.log(`${current === null ? "created  " : "updated  "}${OUT}`);
}
